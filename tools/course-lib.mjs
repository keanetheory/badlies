// Shared by tools/import-course.mjs (OpenStreetMap) and tools/scorecard-course.mjs (scorecards):
// loads the game code, checks a course is playable, writes it and regenerates src/js/02b-real-courses.js.
import fs from 'node:fs'; import vm from 'node:vm';

const root = new URL('../', import.meta.url);
export const P = p => new URL(p, root);
export const CLUB_IDS = ['magpie', 'hightrees', 'rabbit', 'scarlet', 'darker'];
export const THEMES = ['lush', 'links', 'desert'];

// The game's own code, loaded the same way test/sim.mjs does.
const files = ['01-util', '02-course', '04-engine', '05-agents', '06-round', '07-forger'];
vm.runInThisContext(files.map(f => fs.readFileSync(P(`src/js/${f}.js`), 'utf8')).join('\n') +
  '\n;globalThis.BL={importGeo,makeHole,packHole,unpackHole,surfaceAt,NPCS,newRound,startHole,soloHole,hashStr};');
export const BL = globalThis.BL;

export function parseArgs(argv) {
  const args = {};
  for (let i = 0; i < argv.length; i++) {
    const a = argv[i]; if (!a.startsWith('--')) continue;
    const k = a.slice(2), v = argv[i + 1] && !argv[i + 1].startsWith('--') ? argv[++i] : true; args[k] = v;
  }
  return args;
}
export const die = m => { console.error('ERROR: ' + m); process.exit(1); };

export function regenerate() {
  fs.mkdirSync(P('courses/'), { recursive: true });
  const list = fs.readdirSync(P('courses/')).filter(f => f.endsWith('.json')).sort()
    .map(f => JSON.parse(fs.readFileSync(P('courses/' + f), 'utf8')))
    // Map imports carry packed geometry; scorecard courses carry generator specs (much smaller, same result).
    .map(c => ({ id: c.id, name: c.name, theme: c.theme, tag: c.tag, club: c.club || undefined, ...(c.specs ? { specs: c.specs } : { packed: c.holes }) }));
  const js = '// ---------- 02b-real-courses: GENERATED by tools/import-course.mjs from courses/*.json. Do not edit by hand. ----------\n' +
    `BUILTIN.push(...${JSON.stringify(list)});\n`;
  fs.writeFileSync(P('src/js/02b-real-courses.js'), js);
  console.log(`src/js/02b-real-courses.js  ${list.length} imported course${list.length === 1 ? '' : 's'}${list.length ? ': ' + list.map(c => c.id + (c.club ? ` (${c.club})` : '')).join(', ') : ''}`);
}

// Plays every hole with a decent rival and checks the basics. Returns { rows, problems }.
export function checkHoles(holes, theme) {
  const problems = [], rows = [];
  const R = BL.newRound({ format: 'strokeplay', holes: holes.map(h => BL.unpackHole(BL.packHole(h))), total: holes.length, theme, players: [{ ...BL.NPCS[0], skills: { ...BL.NPCS[0].skills } }], seed: 7 });
  for (let k = 0; k < holes.length; k++) {
    R.hi = k; const h = BL.startHole(R);
    if (BL.surfaceAt(h, h.tee) !== 'tee') problems.push(`hole ${k + 1}: the tee isn't on a tee box`);
    if (BL.surfaceAt(h, h.pin) !== 'green') problems.push(`hole ${k + 1}: the pin isn't on the green`);
    if (h.yards < 60 || h.yards > 700) problems.push(`hole ${k + 1}: ${h.yards} yards looks wrong`);
    const tries = [0, 1, 2, 3].map(() => BL.soloHole(R, R.players[0])), avg = tries.reduce((a, b) => a + b, 0) / tries.length;
    if (avg >= h.par + 3.5) problems.push(`hole ${k + 1}: a decent rival averages ${avg.toFixed(1)} on a par ${h.par}; the layout may be broken`);
    rows.push(`  ${String(k + 1).padStart(2)}  par ${h.par}  ${String(h.yards).padStart(3)} yd  ${String(h.bunkers.length).padStart(2)} bunkers  ${h.waters.length ? 'water' : '     '}  ${String(h.trees.length).padStart(3)} trees  rival avg ${avg.toFixed(1)}  ${h.name}`);
  }
  return { rows, problems };
}

export function report({ id, name, club, theme }, holes, rows, notes, problems, extra) {
  console.log(`\n${name}  (${id}${club ? `, home of ${club}` : ''}, ${theme})`);
  if (extra) console.log(extra);
  console.log(`${holes.length} hole${holes.length === 1 ? '' : 's'}, par ${holes.reduce((a, h) => a + h.par, 0)}, ${holes.reduce((a, h) => a + h.yards, 0)} yards`);
  console.log(rows.join('\n'));
  if (notes.length) console.log('\nNotes:\n' + notes.map(n => '  - ' + n).join('\n'));
  if (problems.length) console.log('\nProblems:\n' + problems.map(n => '  - ' + n).join('\n'));
}

// Writes courses/ID.json. A club has one home course, so any other course for the same club loses it.
export function writeCourse(course) {
  fs.mkdirSync(P('courses/'), { recursive: true });
  if (course.club) for (const f of fs.readdirSync(P('courses/')).filter(f => f.endsWith('.json') && f !== course.id + '.json')) {
    const c = JSON.parse(fs.readFileSync(P('courses/' + f), 'utf8'));
    if (c.club === course.club) { c.club = null; fs.writeFileSync(P('courses/' + f), JSON.stringify(c)); console.log(`${c.id} is no longer ${course.club}'s home course.`); }
  }
  fs.writeFileSync(P(`courses/${course.id}.json`), JSON.stringify(course));
  console.log(`\ncourses/${course.id}.json written.`);
  regenerate();
}
